// generate builds every output file from the vendored upstream examples in dir, by path
// relative to the output directory (slash-separated).
func generate(dir string) (map[string][]byte, []*example, error) {
	examples, err := loadExamples(context.Background(), dir)
	if err != nil {
		return nil, nil, err
	}
	files := map[string][]byte{}
	for _, ex := range examples {
		prog, err := build(ex)
		if err != nil {
			return nil, nil, fmt.Errorf("%s: %w", ex.source, err)
		}
		if err := check(prog); err != nil {
			return nil, nil, fmt.Errorf("%s: %w", ex.source, err)
		}
		files["typescript/examples/"+ex.tsFile] = []byte(tsProgram(prog))
		files["python/examples/"+ex.pyModule+".py"] = []byte(pyProgram(prog))
		files["testdata/"+ex.name+".yaml"] = []byte(ex.golden)
		for _, r := range ex.reads {
			for _, lang := range []string{"typescript", "python"} {
				f := lang + "/examples/" + r.file
				if prev, ok := files[f]; ok && string(prev) != string(r.content) {
					return nil, nil, fmt.Errorf("%s: two examples read different files %s", ex.source, r.file)
				}
				files[f] = r.content
			}
		}
	}
	files["typescript/index.ts"] = []byte(tsIndex(examples))
	files["python/__main__.py"] = []byte(pyMain(examples))
	files["python/examples/__init__.py"] = []byte(fmt.Sprintf("\"\"\"The example configurations of docker-agent %s, "+
		"one AgentConfig per module.\n\nGenerated by `make generate_config_types`. Do not edit.\n\"\"\"\n", validate.DockerAgentVersion))
	others, err := os.ReadFile(filepath.Join(dir, otherFilesList))
	if err != nil {
		return nil, nil, fmt.Errorf("%w; run `go run ./internal/schemagen generate` first", err)
	}
	read, err := readFiles(dir)
	if err != nil {
		return nil, nil, err
	}
	readme, err := readmeFile(examples, others, read)
	if err != nil {
		return nil, nil, err
	}
	files["README.md"] = []byte(readme)
	return files, examples, nil
}

// readFiles lists the vendored files that are not configurations: the Markdown and text files
// that configurations read (slash-separated, relative to dir, sorted).
func readFiles(dir string) ([]string, error) {
	var out []string
	err := filepath.WalkDir(dir, func(p string, d fs.DirEntry, err error) error {
		if err != nil || d.IsDir() || d.Name() == "README.md" {
			return err
		}
		rel, err := filepath.Rel(dir, p)
		if ext := filepath.Ext(p); (ext == ".md" || ext == ".txt") && rel != otherFilesList {
			out = append(out, filepath.ToSlash(rel))
		}
		return err
	})
	slices.Sort(out)
	return out, err
}

var languageServer = regexp.MustCompile(`^#\s*yaml-language-server:`)

// isDirective reports whether a comment line is an editor or shell directive rather than
// documentation: a `yaml-language-server` modeline, or a shebang on the first line. They are
// not carried over.
func isDirective(line string, first bool) bool {
	return languageServer.MatchString(line) || (first && strings.HasPrefix(line, "#!"))
}

// leadingComments removes the directives from the comment block at the top of the upstream
// file and returns the block when it stands on its own. When the first key carries it (no
// blank line before the key), it stays with the key.
func leadingComments(dec *render.Decoded) []string {
	drop := func(lines []string) []string {
		var out []string
		for i, l := range lines {
			if !isDirective(l, i == 0) {
				out = append(out, l)
			}
		}
		return trimBlank(out)
	}
	if len(dec.Head) > 0 {
		dec.Head = drop(dec.Head)
		return dec.Head
	}
	if order := dec.Order[""]; len(order) > 0 {
		if c := dec.Comments[render.Path(order[0])]; c != nil {
			c.Head = drop(c.Head)
		}
	}
	return nil
}

// header is the comment block every example file starts with.
func header(ex *example) []string {
	lines := []string{fmt.Sprintf("# Generated from docker-agent %s examples/%s by `make generate_config_types`. Do not edit.",
		validate.DockerAgentVersion, ex.source)}
	for _, t := range ex.twins {
		lines = append(lines, fmt.Sprintf("# examples/%s is the same configuration in HCL.", t))
	}
	if len(ex.head) > 0 {
		if ex.head[0] != "#" {
			lines = append(lines, "#")
		}
		for _, l := range ex.head {
			if l == "" {
				l = "#"
			}
			lines = append(lines, l)
		}
	}
	return lines
}

func readNote(r fileRead) string {
	if r.vars == nil {
		return fmt.Sprintf("The HCL configuration reads this value from %s with docker-agent's file() helper. "+
			"The program reads the copy next to it.", r.file)
	}
	return fmt.Sprintf("The HCL configuration reads this value with docker-agent's file() helper, which renders %s "+
		"as a template. The program reads the copy next to it and replaces each ${name} placeholder the same way.", r.file)
}

func sortedVars(vars map[string]string) []string {
	keys := make([]string, 0, len(vars))
	for k := range vars {
		keys = append(keys, k)
	}
	slices.Sort(keys)
	return keys
}

func tsProgram(prog *program) string {
	ex := prog.ex
	p := &printer{syn: typescript, skip: ex.skipValidation}
	p.comments(0, header(ex))
	p.lines = append(p.lines, "")
	if len(ex.reads) > 0 {
		p.out(0, `import * as fs from "fs";`)
		p.out(0, `import * as path from "path";`)
	}
	p.out(0, `import * as dockeragent from "@ediri/pulumi-docker-agent";`)
	for _, r := range ex.reads {
		v := readVar(r)
		p.lines = append(p.lines, "")
		p.comments(0, []string{noteMarker + readNote(r)})
		file := fmt.Sprintf("path.join(__dirname, %s)", quote(r.file, true))
		if r.vars == nil {
			p.out(0, fmt.Sprintf(`const %s = fs.readFileSync(%s, "utf8");`, v.ts, file))
			continue
		}
		var parts []string
		for _, k := range sortedVars(r.vars) {
			parts = append(parts, typescript.key(&propKey{ts: k})+quote(r.vars[k], true))
		}
		p.out(0, fmt.Sprintf("const %sVars: Record<string, string> = %s;", v.ts, typescript.object(parts)))
		p.out(0, fmt.Sprintf("const %s = fs", v.ts))
		p.out(1, fmt.Sprintf(`.readFileSync(%s, "utf8")`, file))
		p.out(1, fmt.Sprintf(`.replace(/\$\{(\w+)\}/g, (_match, name: string) => %sVars[name]);`, v.ts))
	}
	for _, c := range prog.consts {
		p.lines = append(p.lines, "")
		p.value(0, "const "+c.name.ts+" = ", c.expr, ";", nil)
	}
	p.lines = append(p.lines, "")
	p.out(0, fmt.Sprintf("export const config = new dockeragent.AgentConfig(%s, {", quote(ex.name, true)))
	p.entries(prog.args.entries, 1, false)
	p.comments(1, prog.foot)
	p.out(0, "});")
	p.lines = append(p.lines, "")
	p.out(0, "export const yaml = config.yaml;")
	return p.String()
}

func pyProgram(prog *program) string {
	ex := prog.ex
	p := &printer{syn: python, skip: ex.skipValidation}
	p.comments(0, header(ex))
	p.lines = append(p.lines, "")
	if len(ex.reads) > 0 {
		p.out(0, "import pathlib")
		if slices.ContainsFunc(ex.reads, func(r fileRead) bool { return r.vars != nil }) {
			p.out(0, "import re")
		}
		p.lines = append(p.lines, "")
	}
	p.out(0, "import ediri_docker_agent as dockeragent")
	for _, r := range ex.reads {
		v := readVar(r)
		p.lines = append(p.lines, "")
		p.comments(0, []string{noteMarker + readNote(r)})
		file := fmt.Sprintf("pathlib.Path(__file__).parent / %s", quote(r.file, false))
		if r.vars == nil {
			p.out(0, fmt.Sprintf(`%s = (%s).read_text(encoding="utf-8")`, v.py, file))
			continue
		}
		var parts []string
		for _, k := range sortedVars(r.vars) {
			parts = append(parts, quote(k, false)+": "+quote(r.vars[k], false))
		}
		p.out(0, fmt.Sprintf("%s_file = %s", v.py, file))
		p.out(0, fmt.Sprintf("%s_vars = %s", v.py, python.object(parts)))
		p.out(0, v.py+" = re.sub(")
		p.out(1, `r"\$\{(\w+)\}",`)
		p.out(1, fmt.Sprintf("lambda match: %s_vars[match.group(1)],", v.py))
		p.out(1, fmt.Sprintf(`%s_file.read_text(encoding="utf-8"),`, v.py))
		p.out(0, ")")
	}
	for _, c := range prog.consts {
		p.lines = append(p.lines, "")
		p.value(0, c.name.py+" = ", c.expr, "", nil)
	}
	p.lines = append(p.lines, "")
	p.out(0, "config = dockeragent.AgentConfig(")
	p.out(1, quote(ex.name, false)+",")
	p.entries(prog.args.entries, 1, true)
	p.comments(1, prog.foot)
	p.out(0, ")")
	return p.String()
}

// readVar is the variable that holds the content of a file an HCL example reads.
func readVar(r fileRead) varExpr {
	s := string(r.path)
	f := s[strings.LastIndex(s, ".")+1:]
	return varExpr{ts: f, py: pyName(f)}
}

func tsIndex(examples []*example) string {
	p := &printer{syn: typescript}
	p.comments(0, []string{
		fmt.Sprintf("# Generated by `make generate_config_types` from the example configurations of docker-agent %s.",
			validate.DockerAgentVersion),
		"# Do not edit.",
		"#",
		"# Each module in examples/ builds one example as an AgentConfig. The stack output `configs` maps",
		"# every example name to the docker-agent YAML it renders.",
	})
	p.lines = append(p.lines, "")
	for _, ex := range examples {
		p.out(0, fmt.Sprintf("import * as %s from %s;", ex.tsIdent, quote("./examples/"+strings.TrimSuffix(ex.tsFile, ".ts"), true)))
	}
	p.lines = append(p.lines, "")
	p.out(0, "export const configs = {")
	for _, ex := range examples {
		p.out(1, fmt.Sprintf("%s%s.yaml,", typescript.key(&propKey{ts: ex.name}), ex.tsIdent))
	}
	p.out(0, "};")
	return p.String()
}

func pyMain(examples []*example) string {
	p := &printer{syn: python}
	p.lines = append(p.lines,
		fmt.Sprintf(`"""Every example configuration of docker-agent %s as a typed AgentConfig.`, validate.DockerAgentVersion),
		"",
		"Generated by `make generate_config_types`. Do not edit. Each module in examples/ builds one",
		"example; the stack output `configs` maps every example name to the docker-agent YAML it",
		"renders.",
		`"""`,
		"",
		"import pulumi",
		"",
		"from examples import (",
	)
	modules := make([]string, 0, len(examples))
	for _, ex := range examples {
		modules = append(modules, ex.pyModule)
	}
	slices.Sort(modules)
	for _, m := range modules {
		p.out(1, m+",")
	}
	p.out(0, ")")
	p.lines = append(p.lines, "")
	p.out(0, "pulumi.export(")
	p.out(1, `"configs",`)
	p.out(1, "{")
	for _, ex := range examples {
		p.out(2, fmt.Sprintf("%s: %s.config.yaml,", quote(ex.name, false), ex.pyModule))
	}
	p.out(1, "},")
	p.out(0, ")")
	return p.String()
}
