package main

import (
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/dirien/pulumi-docker-agent/provider/pkg/validate"
)

// otherFileKinds explain the upstream example files that are not agent configurations, by
// path pattern. The first match wins; files that match none are listed as other files.
var otherFileKinds = []struct {
	pattern *regexp.Regexp
	what    string
}{
	{regexp.MustCompile(`(^|/)README\.md$`), "Documentation of the examples."},
	{regexp.MustCompile(`\.(png|jpe?g|gif|svg)$`), "Images used by the documentation."},
	{regexp.MustCompile(`^golibrary/.*\.go$|^chat/.*\.go$`),
		"Go programs that embed docker-agent as a library. The configurations they load are converted like the others."},
	{regexp.MustCompile(`^golibrary/.*\.json$`), "Input data of a Go library example."},
	{regexp.MustCompile(`^dhi/(dhi_mcp_server|node-test)/|^elicitation/server\.py$`),
		"The MCP server and the sample application that the `dhi` and `elicitation` examples run " +
			"(Python, Node.js, Dockerfiles). The configurations themselves are converted."},
	{regexp.MustCompile(`^eval/.*\.json$`), "Recorded sessions and judge cases for `docker agent eval`, not configurations."},
	{regexp.MustCompile(`^rag/.*\.txt$`),
		"The documents the RAG examples index. The programs keep the paths; the files must be next to the YAML where it runs."},
	{regexp.MustCompile(`\.txt$`), "Input text for an example (a document the agent works on)."},
	{regexp.MustCompile(`(^|/)\.(gitignore|env)$`), "Local files of the examples (ignore lists, environment variables)."},
}

// readmeFile writes the README of the generated examples. others is the list of upstream
// example files that are not vendored, read lists the vendored files that configurations read.
func readmeFile(examples []*example, others []byte, read []string) (string, error) {
	v := validate.DockerAgentVersion
	tree := "https://github.com/docker/docker-agent/blob/" + v + "/examples/"
	var b strings.Builder
	w := func(format string, args ...any) { fmt.Fprintf(&b, format, args...) }

	var hcl, twins, skipped, dropped, anchors []*example
	yamlFiles, hclFiles := 0, 0
	for _, ex := range examples {
		yamlFiles++
		if strings.HasSuffix(ex.source, ".hcl") {
			yamlFiles--
			hclFiles++
			hcl = append(hcl, ex)
		}
		hclFiles += len(ex.twins)
		if len(ex.twins) > 0 {
			twins = append(twins, ex)
		}
		if ex.skipValidation != nil {
			skipped = append(skipped, ex)
		}
		if len(ex.dropped) > 0 {
			dropped = append(dropped, ex)
		}
		if len(ex.dec.Anchors) > 0 {
			anchors = append(anchors, ex)
		}
	}

	w("# Docker Agent examples as Pulumi programs\n\n")
	w("<!-- Generated by `make generate_config_types` (provider/internal/examplegen). Do not edit. -->\n\n")
	w("Every example configuration that [docker-agent %s](https://github.com/docker/docker-agent/tree/%s/examples) "+
		"ships (%d YAML and %d HCL files) as a Pulumi program in TypeScript and in Python, %d programs per language. "+
		"Each program builds the configuration with the `AgentConfig` resource and typed inputs only (no `extra`, "+
		"no raw YAML), and keeps the comments of the upstream file, so the programs document the inputs the same way "+
		"the upstream examples document the YAML.\n\n", v, v, yamlFiles, hclFiles, len(examples))
	w("The programs are generated from the docker-agent version in `provider/go.mod` by `make generate_config_types`, " +
		"so they follow every docker-agent upgrade. Do not edit them; change `provider/internal/examplegen` instead. " +
		"To turn your own agent files into programs like these, in any Pulumi language, use the converter: see " +
		"[Converting existing agent files](https://github.com/dirien/pulumi-docker-agent/blob/main/docs/" +
		"installation-configuration.md#converting-existing-agent-files).\n\n")

	w("| Path | Contents |\n|---|---|\n")
	w("| [`typescript/`](typescript) | One Pulumi project. `examples/<name>.ts` builds one example; `index.ts` imports " +
		"all of them and exports the stack output `configs` (example name → rendered YAML). |\n")
	w("| [`python/`](python) | The same in Python: `examples/<module>.py` and `__main__.py`. |\n")
	w("| [`testdata/`](testdata) | `<name>.yaml`: the YAML each program renders. `make test_examples` runs both " +
		"projects and compares every value of `configs` with these files. |\n\n")

	w("## Running the examples\n\n")
	w("The projects use the provider and the SDKs built from this repository: `plugins.providers` points at " +
		"`../../../bin`, and the SDK dependency at the build under `../../../sdk`.\n\n")
	w("```bash\n# From the repository root\nmake provider build_nodejs        # or build_python\n\n")
	w("cd examples/docker-agent-examples/typescript    # or python\n")
	w("export PULUMI_BACKEND_URL=\"file://$HOME/.pulumi-local\" PULUMI_CONFIG_PASSPHRASE=local\n")
	w("pulumi stack init dev\npulumi install --no-plugins\npulumi up\n```\n\n")
	w("Write one configuration to a file and run it with docker-agent:\n\n")
	w("```bash\npulumi stack output configs --json | jq -r '.[\"pirate\"]' > pirate.yaml\ndocker agent run pirate.yaml\n```\n\n")
	w("To use one example on its own, copy `typescript/examples/<name>.ts` as the `index.ts` of a TypeScript project " +
		"(it exports `config` and `yaml`), or `python/examples/<module>.py` as the `__main__.py` of a Python project " +
		"and add `pulumi.export(\"yaml\", config.yaml)`. Outside this repository, install `@ediri/pulumi-docker-agent` " +
		"or `ediri_docker_agent` and drop the `plugins` block from `Pulumi.yaml`.\n\n")
	w("Some examples refer to files that must be next to the YAML where docker-agent runs it, for example the " +
		"documents of the RAG examples or the files of `instruction_file`. The programs keep those paths as they are.\n\n")

	w("## How the YAML maps to the programs\n\n")
	w("- Every key is a typed input: camelCase in TypeScript, snake_case in Python. Map keys (model names, " +
		"environment variables, ...) and free-form values (JSON schemas, provider options, flavors) stay as written.\n")
	w("- YAML shorthands are written in their typed form, as docker-agent reads them: an `instruction` list is one " +
		"string joined with blank lines, `skills: true` is `skills: [\"local\"]`, a `commands` list is one map, " +
		"a `task_budget` object is its total, and a duration in seconds is a `\"<n>s\"` string.\n")
	if len(anchors) > 0 {
		w("- YAML anchors become variables: an alias is a reference to the variable, and a `<<` merge key is a spread "+
			"(`...name` in TypeScript, `**name` in Python). See %s.\n", exampleLinks(anchors))
	}
	w("- Comments are carried over, next to the input they describe. Editor and shell directives (`# yaml-language-server` " +
		"modelines and `#!` lines at the top of a file) are not.\n")
	w("- Multi-line strings are template literals (TypeScript) and triple-quoted strings (Python) whose lines start " +
		"at column 0, so they hold exactly the text of the YAML block.\n")
	w("- The programs are formatted the way Prettier (`--tab-width 4 --print-width 100`) and Black (with its defaults) " +
		"format them.\n")
	for _, ex := range skipped {
		w("- %s sets `skipValidation`: %s. The provider validates the rendered YAML in memory.\n",
			exampleLinks([]*example{ex}), ex.skipValidation.what)
	}
	// Keys left out, grouped by key and reason.
	type leftOut struct{ key, reason string }
	var notes []leftOut
	byNote := map[leftOut][]*example{}
	for _, ex := range dropped {
		for _, d := range ex.dropped {
			n := leftOut{d.key, d.reason}
			if !slices.Contains(byNote[n], ex) {
				if len(byNote[n]) == 0 {
					notes = append(notes, n)
				}
				byNote[n] = append(byNote[n], ex)
			}
		}
	}
	slices.SortFunc(notes, func(a, b leftOut) int { return strings.Compare(a.key+a.reason, b.key+b.reason) })
	for _, n := range notes {
		w("- %s leave out `%s`: %s. A comment in each program shows the upstream line.\n",
			exampleLinks(byNote[n]), n.key, n.reason)
	}
	for _, ex := range twins {
		for _, t := range ex.twins {
			w("- [`%s`](%s%s) is the same configuration as `%s` in HCL (docker-agent loads both identically), "+
				"so %s covers it.\n", t, tree, t, ex.source, exampleLinks([]*example{ex}))
		}
	}
	for _, ex := range hcl {
		for _, r := range ex.reads {
			w("- %s has no YAML version. It reads its `%s` from `%s` with docker-agent's `file()` helper", exampleLinks([]*example{ex}),
				r.path[strings.LastIndex(string(r.path), ".")+1:], r.file)
			if r.vars != nil {
				w(", which renders the file as a template")
			}
			w(". The programs read a copy of the file next to them instead")
			if r.vars != nil {
				w(" and replace its `${name}` placeholders the same way")
			}
			w(".\n")
		}
	}
	w("\n## Examples\n\n")
	w("| Upstream | TypeScript | Python |\n|---|---|---|\n")
	for _, ex := range examples {
		w("| [`%s`](%s%s) | [`%s`](typescript/examples/%s) | [`%s.py`](python/examples/%s.py) |\n",
			ex.source, tree, ex.source, ex.tsFile, ex.tsFile, ex.pyModule, ex.pyModule)
	}

	w("\n## Upstream files that are not converted\n\n")
	w("The other files in docker-agent's `examples/` are not agent configurations:\n\n| Files | What they are |\n|---|---|\n")
	kinds := map[string][]string{}
	var order []string
	for _, f := range strings.Split(string(others), "\n") {
		if f == "" || strings.HasPrefix(f, "#") {
			continue
		}
		what := "Other files."
		for _, k := range otherFileKinds {
			if k.pattern.MatchString(f) {
				what = k.what
				break
			}
		}
		if !slices.Contains(order, what) {
			order = append(order, what)
		}
		kinds[what] = append(kinds[what], f)
	}
	for _, what := range order {
		var links []string
		for _, f := range kinds[what] {
			links = append(links, fmt.Sprintf("[`%s`](%s%s)", f, tree, f))
		}
		w("| %s | %s |\n", strings.Join(links, ", "), what)
	}
	if len(read) > 0 {
		var links []string
		for _, f := range read {
			links = append(links, fmt.Sprintf("[`%s`](%s%s)", f, tree, f))
		}
		w("| %s | Files that configurations read (`instruction_file`, the HCL `file()` helper). The programs keep "+
			"`instruction_file` references as they are; the programs of HCL examples read a copy. |\n", strings.Join(links, ", "))
	}
	return b.String(), nil
}

func exampleLinks(examples []*example) string {
	var out []string
	for _, ex := range examples {
		out = append(out, fmt.Sprintf("`%s` ([TypeScript](typescript/examples/%s), [Python](python/examples/%s.py))",
			ex.name, ex.tsFile, ex.pyModule))
	}
	return strings.Join(out, ", ")
}
